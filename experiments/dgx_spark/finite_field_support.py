#!/usr/bin/env python3
"""Exact finite-field support-forcing atlas for normalized exponents."""
from __future__ import annotations

import argparse
import functools
import json
import math
import time
from pathlib import Path

from provenance import artifact_provenance


def primes_up_to(limit: int) -> list[int]:
    sieve = bytearray(b"\x01") * (limit + 1)
    if limit >= 0:
        sieve[0:2] = b"\x00\x00"
    for p in range(2, int(limit**0.5) + 1):
        if sieve[p]:
            sieve[p * p : limit + 1 : p] = b"\x00" * (((limit - p * p) // p) + 1)
    return [p for p in range(2, limit + 1) if sieve[p]]


@functools.lru_cache(maxsize=None)
def _power_subgroup_by_gcd(q: int, exponent_gcd: int) -> frozenset[int]:
    return frozenset(pow(a, exponent_gcd, q) for a in range(1, q))


def power_subgroup(q: int, exponent: int) -> set[int]:
    return set(_power_subgroup_by_gcd(q, math.gcd(exponent, q - 1)))


@functools.lru_cache(maxsize=None)
def _count_by_gcds(q: int, dx: int, dy: int, dz: int) -> int:
    hx = _power_subgroup_by_gcd(q, dx)
    hy = _power_subgroup_by_gcd(q, dy)
    hz = _power_subgroup_by_gcd(q, dz)
    return sum(1 for x in hx for y in hy if (x + y) % q in hz)


def unit_solution_count(q: int, x: int, y: int, z: int) -> int:
    return _count_by_gcds(q, math.gcd(x, q - 1), math.gcd(y, q - 1), math.gcd(z, q - 1))


def run(kernels: list[int], prime_bound: int) -> dict:
    started = time.perf_counter()
    primes = primes_up_to(prime_bound)
    signature_rows: list[dict] = []
    checks = empty_unit_branches = 0
    zero_branch_failures: list[dict] = []

    for x in kernels:
        for y in kernels:
            for z in kernels:
                forcing: list[dict] = []
                for q in primes:
                    checks += 1
                    if (pow(0, x, q) + pow(1, y, q) - pow(1, z, q)) % q != 0:
                        zero_branch_failures.append({"q": q, "x": x, "y": y, "z": z})
                    count = unit_solution_count(q, x, y, z)
                    if count == 0:
                        empty_unit_branches += 1
                        forcing.append({"prime": q, "conclusion": "q divides A*B*C"})
                if forcing:
                    signature_rows.append({"signature": [x, y, z], "support_forcing_primes": forcing})

    return {
        "schema_version": 1,
        "experiment": "finite_field_support_atlas",
        "parameters": {"kernels": kernels, "prime_bound": prime_bound},
        "signatures_tested": len(kernels) ** 3,
        "signature_prime_checks": checks,
        "unit_empty_branch_occurrences": empty_unit_branches,
        "signatures_with_support_forcing": len(signature_rows),
        "support_forcing": signature_rows,
        "zero_branch_failures": zero_branch_failures,
        "elapsed_seconds": time.perf_counter() - started,
        "interpretation": {
            "bounded_row_meaning": "the producer found no all-unit residue solution for this finite field/signature; the complete atlas is separately regenerated by independent_reproduce.py",
            "not_proved": "signature impossibility; A=0,B=C=1 modulo q survives every modulus",
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--kernels", default="3,4,5,7,11,13")
    parser.add_argument("--prime-bound", type=int, default=251)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    kernels = [int(x) for x in args.kernels.split(",") if x]
    result = run(kernels, args.prime_bound)
    result["provenance"] = artifact_provenance(__file__)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps({
        "checks": result["signature_prime_checks"],
        "support_forcing_signatures": result["signatures_with_support_forcing"],
        "unit_empty_occurrences": result["unit_empty_branch_occurrences"],
        "elapsed_seconds": result["elapsed_seconds"],
    }, sort_keys=True))


if __name__ == "__main__":
    main()
